export const i18n = createI18n({ legacy: false, locale: 'en', fallbackLocale: 'en', messages: { en, fa } })

// Embedded, lang/dir belong on our own root: the host owns <html>.
let localeRoot = null

export function setLocaleRoot(element) {
  localeRoot = element
}

export function setLocale(next) {
  const value = supported.has(next) ? next : 'en'
  i18n.global.locale.value = value
  const root = localeRoot ?? (typeof document !== 'undefined' ? document.documentElement : null)
  if (root) {
    root.lang = value
    root.dir = value === 'fa' ? 'rtl' : 'ltr'
  }
  try { localStorage.setItem(STORAGE_KEY, value) } catch { /* preference remains in memory */ }
}

export function initializeLocale() {
  let stored = 'en'
  try { stored = localStorage.getItem(STORAGE_KEY) ?? 'en' } catch { /* use fallback */ }
  setLocale(stored)
}

export function useI18n() {
  return { locale: i18n.global.locale, t: i18n.global.t, setLocale }
}
